import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import struct
import sys
import tempfile


def load_mapper(path):
    spec = importlib.util.spec_from_file_location("object_inspector_mapper", path)
    if spec is None or spec.loader is None:
        raise ValueError(f"{path}: expected the HadesMapper.py source file")
    mapper = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mapper)
    return mapper


def read_map(mapper, path, source, temporary_output):
    binary = path.read_bytes()
    if len(binary) < 12 or binary[:4] != b"SGB1":
        raise ValueError(f"{path}: invalid compiled map header")
    version, object_count = struct.unpack_from("<II", binary, 4)
    if version != 12:
        raise ValueError(f"{path}: unsupported compiled map version {version}")

    try:
        mapper.DecodeBinaries(str(path.with_suffix("")), str(temporary_output), True)
        decoded = json.loads(temporary_output.with_suffix(".thing_text").read_text())
        things = decoded["Obstacles"]
    except (OSError, ValueError, KeyError, IndexError, struct.error) as error:
        raise ValueError(f"{path}: HadesMapper could not decode the map: {error}") from error

    by_id = {thing["Id"]: thing for thing in things}
    if len(things) != object_count or len(by_id) != object_count:
        raise ValueError(f"{path}: mismatched object count or duplicate authored IDs")

    participants = set()
    for thing in things:
        children = thing["AttachedIDs"]
        target = thing["AttachToID"]
        if children or target != 0:
            participants.add(thing["Id"])
            participants.update(children)
            if target != 0:
                participants.add(target)

    objects = {}
    for object_id in sorted(participants & by_id.keys()):
        thing = by_id[object_id]
        entry = {}
        if thing["Name"] is not None:
            entry["Name"] = thing["Name"]
        if thing["AttachedIDs"]:
            entry["AttachedIDs"] = thing["AttachedIDs"]
        if thing["AttachToID"] != 0:
            entry["AttachToID"] = thing["AttachToID"]
        objects[object_id] = entry

    missing = sorted(participants - by_id.keys())
    if missing:
        print(
            f"Warning: {path.name}: {len(missing)} unresolved authored IDs: "
            + ", ".join(map(str, missing)),
            file=sys.stderr,
        )
    return {
        "Source": source,
        "MapVersion": version,
        "Sha256": hashlib.sha256(binary).hexdigest(),
        "ObjectCount": object_count,
        "Objects": objects,
        "UnresolvedIDs": missing,
    }


def lua_string(value):
    characters = []
    for byte in value.encode("utf-8"):
        if byte in (34, 92):
            characters.append("\\" + chr(byte))
        elif 32 <= byte <= 126:
            characters.append(chr(byte))
        else:
            characters.append(f"\\{byte:03d}")
    return '"' + "".join(characters) + '"'


def lua_ids(values):
    return "{ " + ", ".join(map(str, values)) + " }"


def render_catalog(maps):
    lines = [
        "-- Generated by tools\\export_map_relationships.py from compiled Hades II maps",
        "-- Static authored links only, not live runtime attachments",
        "return {",
        "\tSchemaVersion = 1,",
        "\tMaps = {",
    ]
    for name, data in sorted(maps.items()):
        lines.extend([
            f"\t\t[{lua_string(name)}] = {{",
            f"\t\t\tSource = {lua_string(data['Source'])},",
            f"\t\t\tMapVersion = {data['MapVersion']},",
            f"\t\t\tSha256 = {lua_string(data['Sha256'])},",
            f"\t\t\tObjectCount = {data['ObjectCount']},",
        ])
        if data["UnresolvedIDs"]:
            lines.append(f"\t\t\tUnresolvedIDs = {lua_ids(data['UnresolvedIDs'])},")
        lines.append("\t\t\tObjects = {")
        for object_id, entry in sorted(data["Objects"].items()):
            fields = []
            if "Name" in entry:
                fields.append("Name = " + lua_string(entry["Name"]))
            if "AttachedIDs" in entry:
                fields.append("AttachedIDs = " + lua_ids(entry["AttachedIDs"]))
            if "AttachToID" in entry:
                fields.append("AttachToID = " + str(entry["AttachToID"]))
            lines.append(f"\t\t\t\t[{object_id}] = {{ " + ", ".join(fields) + " },")
        lines.extend(["\t\t\t},", "\t\t},"])
    lines.extend(["\t},", "}", ""])
    return "\n".join(lines)


def write_catalog(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="ascii", newline="\n",
            dir=path.parent, prefix=path.name + ".", suffix=".tmp", delete=False,
        ) as output:
            temporary_path = Path(output.name)
            output.write(content)
        temporary_path.replace(path)
    finally:
        if temporary_path is not None:
            temporary_path.unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description="Export authored Hades II map relationships as Lua data")
    parser.add_argument("--mapper", type=Path, required=True, help="Path to HadesMapper\\HadesMapper.py")
    parser.add_argument(
        "--maps", nargs=2, action="append", required=True,
        metavar=("SOURCE", "DIRECTORY"), help="Source label and compiled map directory; repeat for additional sources",
    )
    parser.add_argument(
        "--output", type=Path,
        default=Path(__file__).resolve().parents[1] / "src" / "Data" / "MapRelationships.lua",
    )
    args = parser.parse_args()

    try:
        mapper = load_mapper(args.mapper.resolve(strict=True))
        maps = {}
        origins = {}
        with tempfile.TemporaryDirectory(prefix="ObjectInspector-MapExport-") as temporary:
            temporary_output = Path(temporary) / "map"
            for source, directory in args.maps:
                root = Path(directory).resolve(strict=True)
                paths = sorted(root.glob("*.thing_bin"))
                if not paths:
                    raise ValueError(f"{root}: no compiled maps found")
                for path in paths:
                    key = path.stem.casefold()
                    if key in origins:
                        raise ValueError(f"Duplicate map name {path.stem}: {origins[key]} and {path}")
                    origins[key] = path
                    maps[path.stem] = read_map(mapper, path, source, temporary_output)
                print(f"{source}: exported {len(paths)} maps")

        write_catalog(args.output, render_catalog(maps))
        objects = sum(data["ObjectCount"] for data in maps.values())
        participants = sum(len(data["Objects"]) for data in maps.values())
        child_links = sum(
            len(entry.get("AttachedIDs", []))
            for data in maps.values() for entry in data["Objects"].values()
        )
        attachment_links = sum(
            "AttachToID" in entry for data in maps.values() for entry in data["Objects"].values()
        )
        print(
            f"Wrote {args.output}: {len(maps)} maps, {objects} authored objects, "
            f"{participants} relationship participants, {child_links} child links, "
            f"{attachment_links} movement attachments"
        )
    except (OSError, ValueError, ImportError) as error:
        parser.exit(1, f"Export failed: {error}\n")


if __name__ == "__main__":
    main()
